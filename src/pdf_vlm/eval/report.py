"""Export evaluation results to CSV / JSON / Markdown."""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any, Sequence

from pdf_vlm.eval.rows import EvalRow
from pdf_vlm.utils.io import ensure_dir, save_json


TABLE_COLS = [
    "group",
    "n",
    "correctness_mean",
    "anls_mean",
    "em_mean",
    "token_f1_mean",
    "recall@3_mean",
    "page_hit@3_mean",
    "gold_answer_contained_rate",
    "latency_ms_mean",
    "peak_rss_mb_max",
    "peak_vram_mb_max",
]


def _fmt(v: Any, digits: int = 4) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        if abs(v) >= 100:
            return f"{v:.1f}"
        return f"{v:.{digits}f}"
    return str(v)


def write_rows_csv(path: Path, rows: Sequence[EvalRow]) -> Path:
    ensure_dir(path.parent)
    flat = [r.to_flat_dict() for r in rows]
    if not flat:
        path.write_text("", encoding="utf-8")
        return path
    keys = list(flat[0].keys())
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(flat)
    return path


def write_table_csv(path: Path, table: Sequence[dict[str, Any]], columns: list[str] | None = None) -> Path:
    ensure_dir(path.parent)
    cols = columns or TABLE_COLS
    # Keep only columns that appear; append extras
    present = set()
    for row in table:
        present.update(row.keys())
    ordered = [c for c in cols if c in present]
    ordered += sorted(present - set(ordered))
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=ordered, extrasaction="ignore")
        w.writeheader()
        for row in table:
            w.writerow({k: row.get(k) for k in ordered})
    return path


def markdown_table(rows: Sequence[dict[str, Any]], columns: list[str] | None = None) -> str:
    if not rows:
        return "_No data._\n"
    cols = columns or [c for c in TABLE_COLS if any(c in r for r in rows)]
    # Prefer subset that exists
    cols = [c for c in cols if any(c in r for r in rows)]
    header = "| " + " | ".join(cols) + " |"
    sep = "| " + " | ".join(["---"] * len(cols)) + " |"
    lines = [header, sep]
    for r in rows:
        lines.append("| " + " | ".join(_fmt(r.get(c)) for c in cols) + " |")
    return "\n".join(lines) + "\n"


def build_markdown_report(
    *,
    run_id: str,
    config_snapshot: dict[str, Any],
    aggregates: dict[str, list[dict[str, Any]]],
    n_rows: int,
    skipped: list[str] | None = None,
) -> str:
    lines: list[str] = [
        f"# Evaluation Report: `{run_id}`",
        "",
        "## Setup",
        "",
        f"- **Seed:** `{config_snapshot.get('seed')}`",
        f"- **Dry run:** `{config_snapshot.get('dry_run')}`",
        f"- **Datasets:** {', '.join(config_snapshot.get('datasets') or [])}",
        f"- **Pipelines:** {', '.join(config_snapshot.get('pipelines') or [])}",
        f"- **Retrieval:** {', '.join(config_snapshot.get('retrievals') or [])}",
        f"- **top_k:** {config_snapshot.get('top_k')}",
        f"- **Examples scored:** {n_rows}",
        "",
    ]
    if skipped:
        lines += ["### Skipped cells", ""]
        for s in skipped:
            lines.append(f"- {s}")
        lines.append("")

    sections = [
        ("Overall", "overall"),
        ("By pipeline (text vs multimodal)", "by_pipeline"),
        ("By retrieval (page vs hierarchical)", "by_retrieval"),
        ("By pipeline × retrieval", "by_cell"),
        ("By page-length bucket", "by_page_bucket"),
        ("By question type", "by_question_type"),
        ("By pipeline × page bucket", "by_pipeline_x_bucket"),
        ("Full cell breakdown", "by_full_cell"),
    ]
    for title, key in sections:
        table = aggregates.get(key) or []
        lines += [f"## {title}", "", markdown_table(table), ""]

    lines += [
        "---",
        "",
        "_Generated by `pdf_vlm.eval.harness`. Config snapshot saved alongside this report._",
        "",
    ]
    return "\n".join(lines)


def export_reports(
    run_dir: Path,
    *,
    run_id: str,
    rows: list[EvalRow],
    aggregates: dict[str, list[dict[str, Any]]],
    config_snapshot: dict[str, Any],
    seed_snapshot: dict[str, Any],
    skipped: list[str] | None = None,
    report_dir: Path | None = None,
) -> dict[str, str]:
    """Write CSV/JSON/Markdown artifacts. Returns path map."""
    ensure_dir(run_dir)
    report_dir = ensure_dir(report_dir or run_dir)

    paths: dict[str, str] = {}

    pred_csv = write_rows_csv(run_dir / "predictions.csv", rows)
    paths["predictions_csv"] = str(pred_csv)

    save_json(run_dir / "predictions.json", [r.model_dump(mode="json") for r in rows])
    paths["predictions_json"] = str(run_dir / "predictions.json")

    save_json(run_dir / "aggregates.json", aggregates)
    paths["aggregates_json"] = str(run_dir / "aggregates.json")

    for name, table in aggregates.items():
        p = write_table_csv(run_dir / "tables" / f"{name}.csv", table)
        paths[f"table_{name}"] = str(p)

    md = build_markdown_report(
        run_id=run_id,
        config_snapshot=config_snapshot,
        aggregates=aggregates,
        n_rows=len(rows),
        skipped=skipped,
    )
    md_path = report_dir / f"{run_id}.md"
    ensure_dir(md_path.parent)
    md_path.write_text(md, encoding="utf-8")
    # Also copy into run_dir
    (run_dir / "report.md").write_text(md, encoding="utf-8")
    paths["report_md"] = str(md_path)
    paths["report_md_run"] = str(run_dir / "report.md")

    save_json(run_dir / "config_snapshot.json", config_snapshot)
    save_json(run_dir / "seed_snapshot.json", seed_snapshot)
    paths["config_snapshot"] = str(run_dir / "config_snapshot.json")
    paths["seed_snapshot"] = str(run_dir / "seed_snapshot.json")

    summary = {
        "run_id": run_id,
        "n_rows": len(rows),
        "n_skipped": len(skipped or []),
        "paths": paths,
        "overall": (aggregates.get("overall") or [{}])[0],
    }
    save_json(run_dir / "summary.json", summary)
    paths["summary"] = str(run_dir / "summary.json")
    return paths
